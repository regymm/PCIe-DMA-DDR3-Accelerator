/*This module is created by Mohamed Khaled for testing the ZTACHIP SoC through applying real time stimulus through 
a camera emulator for the module OV7670 connected with ROM storing the images*/
module camera_emu (sioc, siod, rst_n, pwdn, xclk, pclk, data, hsync_cam, tvalid_cam, tready_in);
    //defining ports
    input wire pclk; //camera system clock
    input wire rst_n;//active low reset
    input wire pwdn, xclk;///unused control signals
    input wire sioc, siod;//unused i2c signals intended for initialization
    input wire tready_in;//Post-camera stage tready
    output wire [7:0] data;//pixels are generated byte by byte in RGB 555 format
    output wire hsync_cam;//image rows synchronizer
    output wire tvalid_cam;//image pixels valid signal
/*******some observations***************/
    //camera is sending RGB555 : B...G...R
    //image size is 680 columns x 480 rows
    //sys_clk: input system clock
    //rst_n: active low camera reset
    //pwdn: active low power mode
    //tuser is unused but set to zero
    //each pixel processing takes two cycles
    // after 262,143,000 ns reset is inactive--calcualted on 2ns clock cycle period
    // after  356508 of pclk cycles initialization is finished
/**************************************************declaring important signals*******************************/
    wire [7:0] data_rom;//placeholder for out data
    reg hsync_cam_reg;//placeholder for hsync_cam
    reg tvalid_cam_reg;//placeholder for tvalid_cam
    reg [19:0] init_cycles;//waiting for initialization to finish
    reg [11:0] bytes_sent;//counting sent bytes from the emulator side
    reg go_emu, init_done, operation_start;//important flags
    reg [8:0] col_count, row_count;//for controlling data retrieval from RAMs
    reg [19:0] i;//rom address counter
    //instantiating the testing images ROMs
    camera_rom r1 (.pclk(pclk), .rst_n(rst_n), .address(i), .data_out(data_rom));
    //handling the init_cycles counter
    always @(posedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            init_cycles<=0;
        end
        else begin
            if(init_cycles<356509) begin
                init_cycles<=init_cycles+1;
            end
            if(go_emu) begin
                init_cycles<=356510;
            end
        end
    end
    //flag for checking the camera initialization is done
    always @(posedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            init_done<=0;
        end
        else begin
            if(init_cycles==356508) begin
                init_done<=1;
            end
        end
    end
    //handling the operation_start flag
    always @(posedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            operation_start<=0;//reset
        end
        else begin
            if(init_cycles==356508&&bytes_sent==0) begin//for the first very row synchronization
                operation_start<=1;
            end
            else begin
                if(operation_start&&tready_in) begin//lowering the flag again after properly starting sending the row
                    operation_start<=0;
                end
                else if(!operation_start&&hsync_cam_reg&&bytes_sent==1280) begin//asserting the flag for next rows
                    operation_start<=1;
                end
            end
        end
    end
    //handling the hsync output
    always @(posedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            hsync_cam_reg<=0;//reset
        end
        else begin
            if(operation_start&&tready_in) begin//giving the start condition for the first very row
                hsync_cam_reg<=1;
            end
            else if(!operation_start&&hsync_cam_reg&&bytes_sent==1280) begin
                hsync_cam_reg<=0;//lowering the signal for future rows 
            end
        end
    end
    //handling the go_emu flag
    always @(posedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            go_emu<=0;//reset
        end
        else begin
            if(hsync_cam&&!operation_start&&bytes_sent<1280&&tvalid_cam) begin
                go_emu<=1;//adding extra cycle delay for the first very pixel to adapt with the receiver behaviour
            end
        end
    end
    //valid data behaviour
    always @(negedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            tvalid_cam_reg<=0;
        end
        else begin
            if(hsync_cam_reg&&!operation_start&&bytes_sent<1280) begin
                tvalid_cam_reg<=1;
            end
            else begin
                tvalid_cam_reg<=0;
            end
        end
    end
    //controlling the data sending
    always @(negedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            bytes_sent<=0;
        end
        else begin
            if((hsync_cam&&!operation_start&&tvalid_cam||go_emu)&&bytes_sent<1280&&tready_in) begin
                    bytes_sent<=bytes_sent+1;
            end
            else begin
                bytes_sent<=0;
            end
        end
    end

    always @(negedge pclk or negedge rst_n) begin
        if(!rst_n) begin
            i<=0;
        end
        else begin
            if((hsync_cam&&!operation_start&&tvalid_cam||go_emu)&&bytes_sent<1280&&tready_in) begin
                if(i==614399) begin
                    i<=0;
                end
                else begin
                   i<=i+1;//getting next byte from ROM 
                end
            end
        end
    end
    assign hsync_cam = hsync_cam_reg;
    assign data = data_rom;
    assign tvalid_cam = tvalid_cam_reg;
endmodule //camera_emu